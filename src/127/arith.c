/// NOTE: transpose8xN works on row-major matrices. A row-major 8 x m matrix
///     is the same as a column-major m x 8 matrix.
uint32_t test_gf127_matrix_transpose8xN() {
    const uint32_t n = 8;
    const uint32_t m = 9;
    uint8_t *A  = (uint8_t *)malloc(n * m);
    uint8_t *B1 = (uint8_t *)malloc(n * m);

    // NOTE: this is important: LESS assumes that the input matrix is square
    uint8_t *B2 = (uint8_t *)malloc(m * m);
    for (uint32_t i = 0; i < n*m; i++) { A[i] = i; }

    // A as column-major: m x n, B1: n x m column-major = m x n row-major
    gf127_matrix_transpose(B1, A, m, n);
    gf127_matrix_transpose8xN(B2, A, m);

    for (uint32_t i = 0; i < m; i++) {
        for (uint32_t j = 0; j < n; j++) {
            // row i, column j of the row-major m x n result
            const uint8_t t1 = B1[i*n + j];
            const uint8_t t2 = B2[i*m + j];
            const uint8_t t3 = A[j*m + i];
            if ((t1 != t2) || (t1 != t3)) {
                gf127_matrix_print(A, m, n);
                gf127_matrix_print(B1, n, m);
                printf("error: test_gf127_matrix_transpose8xN: %d %d\n", i, j);
                return 1;
            }
        }
    }

    free(A); free(B1); free(B2);
    return 0;
}

