int test_scalar() {
    for (uint32_t a = 0; a < PRIME; a++) {
        if (gf127_add(a, gf127_neg(a)) != 0) {
            printf("error gf127_neg\n");
            return 1;
        }
        if ((a != 0) && (gf127_mul(a, gf127_inv(a)) != 1)) {
            printf("error gf127_inv\n");
            return 1;
        }
        for (uint32_t b = 0; b < PRIME; b++) {
            if (gf127_add(a, b) != (a + b) % PRIME ||
                gf127_sub(a, b) != (a + PRIME - b) % PRIME ||
                gf127_mul(a, b) != (a * b) % PRIME ||
                gf127_sub(gf127_add(a, b), b) != a) {
                printf("error gf127_add/sub/mul\n");
                return 1;
            }
        }
    }
    if (gf127_inv(0) != 0) {
        printf("error gf127_inv(0)\n");
        return 1;
    }
    return 0;
}

/// checks all ref vector functions against naive implementations
int test_vector_ref() {
    for (uint32_t l = 0; l < NR_TEST_LENGTHS; l++) {
        const uint32_t n = test_lengths[l];
        gf127 *a = gf127_vector_alloc(n), *b = gf127_vector_alloc(n),
              *c = gf127_vector_alloc(n), *d = gf127_vector_alloc(n);
        gf127_vector_random(a, n);
        gf127_vector_random(b, n);
        gf127_vector_copy(c, a, n);
        for (uint32_t i = 0; i < n; i++) {
            if (gf127_vector_get(c, i) != a[i] || a[i] >= PRIME) {
                printf("error gf127_vector_copy/random\n");
                return 1;
            }
        }

        const gf127 s = rand() % PRIME;
        gf127_vector_add(c, b, n);
        gf127_vector_scalar_add_v2(d, a, s, b, n);
        uint32_t acc = 0;
        for (uint32_t i = 0; i < n; i++) {
            acc = (acc + a[i]*b[i]) % PRIME;
            if (c[i] != (a[i] + b[i]) % PRIME || d[i] != (a[i] + s*b[i]) % PRIME) {
                printf("error gf127_vector_add/scalar_add_v2\n");
                return 1;
            }
        }
        if (acc != gf127_vector_mul_acc(a, b, n)) {
            printf("error gf127_vector_mul_acc\n");
            return 1;
        }

        gf127_vector_copy(c, a, n);
        gf127_vector_scalar_add(c, s, b, n);
        for (uint32_t i = 0; i < n; i++) {
            if (c[i] != d[i]) {
                printf("error gf127_vector_scalar_add\n");
                return 1;
            }
        }

        gf127_vector_set(c, 0, 7);
        gf127_vector_zero(d, n);
        if (gf127_vector_get(c, 0) != 7 || gf127_vector_mul_acc(d, a, n) != 0) {
            printf("error gf127_vector_set/zero\n");
            return 1;
        }
        free(a); free(b); free(c); free(d);
    }
    return 0;
}

/// checks a set of SIMD vector functions against the ref implementation
int test_vector_simd(const char *name,
                     void (*add)(gf127 *, const gf127 *, const uint32_t),
                     void (*add_v2)(gf127 *, const gf127 *, const gf127 *, const uint32_t),
                     void (*scalar_add)(gf127 *, const gf127, const gf127 *, const uint32_t),
                     void (*scalar_add_v2)(gf127 *, const gf127 *, const gf127, const gf127 *, const uint32_t),
                     gf127 (*mul_acc)(const gf127 *, const gf127 *, const uint32_t)) {
    for (uint32_t l = 0; l < NR_TEST_LENGTHS; l++) {
        const uint32_t n = test_lengths[l];
        gf127 *a = gf127_vector_alloc(n), *b = gf127_vector_alloc(n),
              *c1 = gf127_vector_alloc(n), *c2 = gf127_vector_alloc(n);
        gf127_vector_random(a, n);
        gf127_vector_random(b, n);
        const gf127 s = rand() % PRIME;

        gf127_vector_copy(c1, a, n); gf127_vector_add(c1, b, n);
        gf127_vector_copy(c2, a, n); add(c2, b, n);
        if (memcmp(c1, c2, n)) { printf("error %s: vector_add n=%u\n", name, n); return 1; }

        gf127_vector_random(c2, n);
        add_v2(c2, a, b, n);
        if (memcmp(c1, c2, n)) { printf("error %s: vector_add_v2 n=%u\n", name, n); return 1; }

        gf127_vector_copy(c1, a, n); gf127_vector_scalar_add(c1, s, b, n);
        gf127_vector_copy(c2, a, n); scalar_add(c2, s, b, n);
        if (memcmp(c1, c2, n)) { printf("error %s: vector_scalar_add n=%u\n", name, n); return 1; }

        gf127_vector_random(c2, n);
        scalar_add_v2(c2, a, s, b, n);
        if (memcmp(c1, c2, n)) { printf("error %s: vector_scalar_add_v2 n=%u\n", name, n); return 1; }

        if (gf127_vector_mul_acc(a, b, n) != mul_acc(a, b, n)) {
            printf("error %s: vector_mul_acc n=%u\n", name, n);
            return 1;
        }
        free(a); free(b); free(c1); free(c2);
    }
    return 0;
}

/// checks the ref matrix functions
int test_matrix_ref() {
    for (uint32_t t = 0; t < NR_TEST_SHAPES; t++) {
        const uint32_t n = test_shapes[t][0], k = test_shapes[t][1], m = test_shapes[t][2];
        gf127 *A  = gf127_matrix_alloc(n, k), *At = gf127_matrix_alloc(k, n),
              *A2 = gf127_matrix_alloc(n, k), *B  = gf127_matrix_alloc(k, m),
              *I  = gf127_matrix_alloc(k, k), *C1 = gf127_matrix_alloc(n, m),
              *C2 = gf127_matrix_alloc(n, m), *C3 = gf127_matrix_alloc(n, m);
        gf127_matrix_random(A, n, k);
        gf127_matrix_random(B, k, m);
        gf127_matrix_random(C3, n, m);

        // A*I == A
        gf127_matrix_id(I, k, k);
        gf127_matrix_mul(A2, A, I, n, k, k);
        if (memcmp(A, A2, n*k)) { printf("error gf127_matrix_id/mul\n"); return 1; }

        // (A^T)^T == A
        gf127_matrix_transpose(At, A, n, k);
        gf127_matrix_transpose(A2, At, k, n);
        if (memcmp(A, A2, n*k)) { printf("error gf127_matrix_transpose\n"); return 1; }
        for (uint32_t i = 0; i < n; i++) {
            for (uint32_t j = 0; j < k; j++) {
                if (gf127_matrix_get(A, n, i, j) != gf127_matrix_get(At, k, j, i)) {
                    printf("error gf127_matrix_transpose 2\n"); return 1;
                }
            }
        }

        // add_mul == mul + add
        gf127_matrix_mul(C1, A, B, n, k, m);
        gf127_matrix_add(C2, C1, C3, n, m);
        gf127_matrix_copy(C1, C3, n, m);
        gf127_matrix_add_mul(C1, A, B, n, k, m);
        if (memcmp(C1, C2, n*m)) { printf("error gf127_matrix_add_mul\n"); return 1; }

        // naive product
        for (uint32_t i = 0; i < n; i++) {
            for (uint32_t j = 0; j < m; j++) {
                uint32_t s = 0;
                for (uint32_t l = 0; l < k; l++) {
                    s += A[l*n + i] * B[j*k + l];
                }
                if (gf127_add(s % PRIME, C3[j*n + i]) != C2[j*n + i]) {
                    printf("error gf127_matrix_mul naive\n"); return 1;
                }
            }
        }

        // add_scalar
        const gf127 s = rand() % PRIME;
        gf127_matrix_copy(C1, C3, n, m);
        gf127_matrix_add_scalar(C1, s, C2, n, m);
        for (uint32_t i = 0; i < n*m; i++) {
            if (C1[i] != (C3[i] + s*C2[i]) % PRIME) { printf("error gf127_matrix_add_scalar\n"); return 1; }
        }

        free(A); free(At); free(A2); free(B); free(I); free(C1); free(C2); free(C3);
    }
    return 0;
}

/// checks a set of SIMD matrix functions against the ref implementation
int test_matrix_simd(const char *name,
                     void (*add)(gf127 *, const gf127 *, const gf127 *, const uint32_t, const uint32_t),
                     void (*add_scalar)(gf127 *, const gf127, const gf127 *, const uint32_t, const uint32_t),
                     void (*mul)(gf127 *, const gf127 *, const gf127 *, const uint32_t, const uint32_t, const uint32_t),
                     void (*add_mul)(gf127 *, const gf127 *, const gf127 *, const uint32_t, const uint32_t, const uint32_t)) {
    for (uint32_t t = 0; t < NR_TEST_SHAPES; t++) {
        const uint32_t n = test_shapes[t][0], k = test_shapes[t][1], m = test_shapes[t][2];
        gf127 *A  = gf127_matrix_alloc(n, k), *B  = gf127_matrix_alloc(k, m),
              *C1 = gf127_matrix_alloc(n, m), *C2 = gf127_matrix_alloc(n, m),
              *C3 = gf127_matrix_alloc(n, m), *D  = gf127_matrix_alloc(n, m);
        gf127_matrix_random(A, n, k);
        gf127_matrix_random(B, k, m);
        gf127_matrix_random(C3, n, m);
        gf127_matrix_random(D, n, m);
        const gf127 s = rand() % PRIME;

        gf127_matrix_mul(C1, A, B, n, k, m);
        gf127_matrix_random(C2, n, m);
        mul(C2, A, B, n, k, m);
        if (memcmp(C1, C2, n*m)) { printf("error %s: matrix_mul\n", name); return 1; }

        gf127_matrix_copy(C1, C3, n, m); gf127_matrix_add_mul(C1, A, B, n, k, m);
        gf127_matrix_copy(C2, C3, n, m); add_mul(C2, A, B, n, k, m);
        if (memcmp(C1, C2, n*m)) { printf("error %s: matrix_add_mul\n", name); return 1; }

        gf127_matrix_add(C1, C2, C3, n, m);
        add(C2, C2, C3, n, m);
        if (memcmp(C1, C2, n*m)) { printf("error %s: matrix_add\n", name); return 1; }

        gf127_matrix_copy(C1, C3, n, m); gf127_matrix_add_scalar(C1, s, D, n, m);
        gf127_matrix_copy(C2, C3, n, m); add_scalar(C2, s, D, n, m);
        if (memcmp(C1, C2, n*m)) { printf("error %s: matrix_add_scalar\n", name); return 1; }

        free(A); free(B); free(C1); free(C2); free(C3); free(D);
    }
    return 0;
}

